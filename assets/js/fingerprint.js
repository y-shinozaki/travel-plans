/**
 * リモートのファイル本文から作る指紋。**時計に依存しない競合検出のためだけにある。**
 *
 * なぜ要るか（設計書 §13「時計ずれ」）:
 *
 * base に入れていた updatedAt は、公開した端末の時計で押される。押す端末が
 * 複数あるので順序関係が保たれない ── A の時計が遅れていれば、A があとから
 * 公開した版の updatedAt が B の版より古くなり、B の base を下回る。
 * 突き合わせは「リモートは進んでいない」と判断し、**A の公開を黙って上書きする。**
 *
 * 指紋は「同じ内容か違う内容か」しか答えないが、競合検出に要るのはまさにそれで、
 * しかも時計をひとつも見ない。**新旧の判定には使えない**（どちらが新しいかは
 * 分からない）ので、起動時の判断（sync-decide.js）は updatedAt のままにしてある。
 *
 * 暗号学的強度は要らない ── 守る相手は「別の端末がすでに公開していたこと」で、
 * 攻撃者が衝突を作れるかではない（作れたところで、書き込みには結局トークンが要る）。
 * FNV-1a を 2 レーン回して 64 ビットぶん取る。1 レーン（32 ビット）だと、
 * 旅程 1 本の改版を何十回も重ねるうちに偶然の一致が現実的な確率で起こりうる。
 */

/** 末尾の空白だけ落とす。改行の有無で指紋が割れると、公開が毎回 409 になる。 */
const normalize = (text) => String(text).replace(/\s+$/, "");

export function fingerprint(text) {
  const src = normalize(text);
  // 別々の初期値から回して連結する（同じ初期値の 2 本は同じ値になり意味が無い）
  let a = 0x811c9dc5;
  let b = 0x01000193;
  for (let i = 0; i < src.length; i++) {
    const code = src.charCodeAt(i);
    a = Math.imul(a ^ code, 0x01000193) >>> 0;
    b = Math.imul(b ^ code, 0x85ebca6b) >>> 0;
  }
  return a.toString(16).padStart(8, "0") + b.toString(16).padStart(8, "0");
}
